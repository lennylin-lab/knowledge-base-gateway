// TestAdminCredentialTenantList pins the mandatory tenant predicate on
// listings and the audit rows for authentication events plus the throttled
// last-use stamp.
func TestAdminCredentialTenantListAndBookkeeping(t *testing.T) {
	s, _, db := newAdminTestStore(t)
	ctx := context.Background()
	now := time.Now()

	recEU, plainEU := adminTestRecord(t, "adm_t_1", "euops", []string{"viewer"}, "tenant_eu", time.Time{})
	if err := s.Create(ctx, recEU, mgmt.AdminOp{Action: "admin_credential_create"}); err != nil {
		t.Fatalf("create eu: %v", err)
	}
	recHome, _ := adminTestRecord(t, "adm_t_2", "homeops", []string{"viewer"}, "tenant_default", time.Time{})
	if err := s.Create(ctx, recHome, mgmt.AdminOp{Action: "admin_credential_create"}); err != nil {
		t.Fatalf("create home: %v", err)
	}

	all, err := s.List(ctx, "", "")
	if err != nil || len(all) != 2 {
		t.Fatalf("global list: %v %d", err, len(all))
	}
	eu, err := s.List(ctx, "", "tenant_eu")
	if err != nil || len(eu) != 1 || eu[0].ID != recEU.ID {
		t.Fatalf("tenant-predicated list must return only the tenant rows: %v %+v", err, eu)
	}

	// Authentication bookkeeping: success rows carry the credential, failure
	// rows carry the reason class; last-used stamps are throttled.
	p := recEU.Principal()
	s.LogAuth(ctx, p, true, "", now)
	s.LogAuth(ctx, p, false, "revoked", now)
	if countAdminAudit(t, db, "admin_auth") != 1 || countAdminAudit(t, db, "admin_auth_failed") != 1 {
		t.Fatal("authentication events must be audited")
	}
	s.TouchLastUsed(ctx, recEU.ID, now)
	var lastUsed sql.NullTime
	if err := db.QueryRow(`SELECT last_used_at FROM admin_credentials WHERE id = $1`, recEU.ID).Scan(&lastUsed); err != nil {
		t.Fatalf("read last_used: %v", err)
	}
	if !lastUsed.Valid {
		t.Fatal("last_used_at must be stamped")
	}
	// Inside the throttle window the stamp does not move.
	s.TouchLastUsed(ctx, recEU.ID, now.Add(10*time.Second))
	var same sql.NullTime
	if err := db.QueryRow(`SELECT last_used_at FROM admin_credentials WHERE id = $1`, recEU.ID).Scan(&same); err != nil {
		t.Fatalf("re-read last_used: %v", err)
	}
	if !same.Valid || !same.Time.Equal(lastUsed.Time) {
		t.Fatal("last-used stamp must be throttled within the window")
	}
	_ = plainEU
}

// TestAdminCredentialSchemaChecks pins the migration's database boundary:
// scope values outside the closed vocabulary and empty grant sets are
// rejected by the CHECK constraints, never by application logic.
func TestAdminCredentialSchemaChecks(t *testing.T) {
	_, _, db := newAdminTestStore(t)
	cases := []struct {
		name    string
		scopes  string
		wantErr bool
	}{
		{"closed-vocabulary ok", `ARRAY['viewer','operator']`, false},
		{"invented scope rejected", `ARRAY['superuser']`, true},
		{"empty grant set rejected", `ARRAY[]::text[]`, true},
	}
	for _, tc := range cases {
		_, err := db.Exec(`
			INSERT INTO admin_credentials (id, admin_subject, credential_hash, credential_prefix, scopes, status, created_at)
			VALUES ('adm_check_'||$1, 's', decode(md5($1), 'hex'), 'kba_xx', `+tc.scopes+`, 'active', now())`, tc.name)
		if tc.wantErr && err == nil {
			t.Errorf("%s: schema must reject the row", tc.name)
		}
		if !tc.wantErr && err != nil {
			t.Errorf("%s: valid row rejected: %v", tc.name, err)
		}
	}
}

// TestAdminCredentialUnknownTenant pins the FK translation: creating a
// credential for an unknown tenant answers the domain error (a clean 400
// upstream), not a raw driver failure.
func TestAdminCredentialUnknownTenant(t *testing.T) {
	s, _, _ := newAdminTestStore(t)
	rec, _ := adminTestRecord(t, "adm_fk_1", "ops", []string{"viewer"}, "tenant_missing", time.Time{})
	err := s.Create(context.Background(), rec, mgmt.AdminOp{Action: "admin_credential_create"})
	if !errors.Is(err, adminauth.ErrUnknownTenant) {
		t.Fatalf("unknown tenant must translate to ErrUnknownTenant, got %v", err)
	}
}

func containsAll(haystack string, needles ...string) bool {
	for _, n := range needles {
		if !strings.Contains(haystack, n) {
			return false
		}
	}
	return true
}
